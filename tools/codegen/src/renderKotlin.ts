import type { Declaration, KotlinType, Model, Property } from "./buildModels.ts";
import { pascalCase } from "./naming.ts";

export const MODEL_PACKAGE = "net.neednot.renttracker.model";
export const GENERATED_HEADER = "// Generated by tools/codegen from convex function-spec. Do not edit.";

const INDENT = "    ";

export function renderModelFiles(models: Model[]): Map<string, string> {
  const packageOf = new Map(models.map((model) => [model.declaration.name, model.packageName]));
  const files = new Map<string, string>();
  for (const model of models) {
    const path = `${model.packageName.replaceAll(".", "/")}/${model.declaration.name}.kt`;
    files.set(path, renderModel(model, packageOf));
  }
  return files;
}

function renderModel(model: Model, packageOf: Map<string, string>): string {
  const imports = new Set(["kotlinx.serialization.Serializable"]);
  const body =
    model.declaration.kind === "class"
      ? renderClass(model.declaration, imports, model.packageName, packageOf)
      : renderEnum(model.declaration, imports);
  const importLines = [...imports].sort().map((name) => `import ${name}`);
  return [
    GENERATED_HEADER,
    "",
    `package ${MODEL_PACKAGE}.${model.packageName}`,
    "",
    ...importLines,
    "",
    "@Serializable",
    ...body,
    "",
  ].join("\n");
}

function renderClass(
  declaration: Declaration & { kind: "class" },
  imports: Set<string>,
  ownPackage: string,
  packageOf: Map<string, string>,
): string[] {
  const lines = [`data class ${declaration.name}(`];
  for (const property of declaration.properties) {
    if (property.name !== property.serialName) {
      imports.add("kotlinx.serialization.SerialName");
      lines.push(`${INDENT}@SerialName("${property.serialName}")`);
    }
    lines.push(`${INDENT}val ${property.name}: ${renderProperty(property, imports, ownPackage, packageOf)},`);
  }
  lines.push(")");
  return lines;
}

function renderProperty(
  property: Property,
  imports: Set<string>,
  ownPackage: string,
  packageOf: Map<string, string>,
): string {
  const type = renderType(property.type, imports, ownPackage, packageOf);
  return property.hasDefaultNull ? `${type} = null` : type;
}

function renderType(
  type: KotlinType,
  imports: Set<string>,
  ownPackage: string,
  packageOf: Map<string, string>,
): string {
  switch (type.kind) {
    case "builtin":
      if (type.name === "JsonElement") {
        imports.add("kotlinx.serialization.json.JsonElement");
      }
      return type.name;
    case "list":
      return `List<${renderType(type.item, imports, ownPackage, packageOf)}>`;
    case "map":
      return `Map<String, ${renderType(type.value, imports, ownPackage, packageOf)}>`;
    case "nullable":
      return `${renderType(type.inner, imports, ownPackage, packageOf)}?`;
    case "declared": {
      const typePackage = packageOf.get(type.name);
      if (typePackage !== undefined && typePackage !== ownPackage) {
        imports.add(`${MODEL_PACKAGE}.${typePackage}.${type.name}`);
      }
      return type.name;
    }
  }
}

function renderEnum(declaration: Declaration & { kind: "enum" }, imports: Set<string>): string[] {
  imports.add("kotlinx.serialization.SerialName");
  const lines = [`enum class ${declaration.name} {`];
  declaration.values.forEach((value, index) => {
    if (index > 0) {
      lines.push("");
    }
    lines.push(`${INDENT}@SerialName("${value}")`, `${INDENT}${pascalCase(value)},`);
  });
  lines.push("}");
  return lines;
}
